struct OfficeCellCoordinate: Hashable, Codable, Equatable {
    let row: Int
    let column: Int

    var name: String { "\(Self.columnName(column))\(row + 1)" }

    static func columnName(_ column: Int) -> String {
        var value = column + 1
        var result = ""
        while value > 0 {
            value -= 1
            result = String(UnicodeScalar(65 + value % 26)!) + result
            value /= 26
        }
        return result
    }
}

